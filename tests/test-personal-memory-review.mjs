import assert from 'node:assert/strict';
import { mkdtemp, mkdir, readFile, writeFile, rm, rename } from 'node:fs/promises';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { setIsolatedTestHome } from './isolate-test-environment.mjs';
const home=await mkdtemp(join(tmpdir(),'personal-memory-review-'));setIsolatedTestHome(home);
process.env.REMOTELAB_MEMORY_DIR=join(home,'memory');
try {
  const {loadAuthDocument,updateAuthDocument}=await import('../lib/auth-config.mjs');
  await updateAuthDocument(d=>{for(const name of ['alice','bob'])d.people.push({id:'person_'+name,name,credentials:[],identities:[{id:'identity_'+name,kind:'web',subjectId:name}],preferences:{personalMemory:{version:1,revision:1,enabled:true,conversational:true}}});});
  const memoryDir=process.env.REMOTELAB_MEMORY_DIR;
  await mkdir(memoryDir,{recursive:true});
  await writeFile(join(memoryDir,'learning-policy.json'),JSON.stringify({version:1,enabled:true,profiles:true,handbook:true,context:true,personIds:['person_alice','person_bob'],handbookPersonIds:['person_bob']}));
  const m=await import('../chat/memory-learning.mjs');
  const {listPersonalMemories:list,reviewPersonalMemory:review}=await import('../chat/personal-memory-review.mjs');
  const {handlePersonalMemorySettings:route}=await import('../chat/router-personal-memory-settings.mjs');
  const alice={personId:'person_alice',identityId:'identity_alice',authKind:'password'};
  const bob={personId:'person_bob',identityId:'identity_bob',authKind:'password'};
  const actor=async a=>({...a,authDocument:await loadAuthDocument({persistMigration:false})});
  const source=[{sessionId:'fixture',runId:'run_fixture',seq:1,type:'user',output:'以后解释时先给结论，请记住'}];
  await m.applyLearningUpdates({...await actor(alice),updates:[{key:'conclusions',kind:'habit',content:'ALICE_ONLY',cues:['解释'],conditions:'解释时',evidence:[{seq:1,quote:source[0].output}]}],sources:source});
  await m.applyLearningUpdates({...await actor(bob),updates:[{key:'bob-only',kind:'habit',content:'BOB_PRIVATE',cues:['解释'],conditions:'解释时',evidence:[{seq:1,quote:source[0].output}]}],sources:source});
  let entries=(await list(alice)).entries;assert.equal(entries.length,1);assert.equal(entries[0].content,'ALICE_ONLY');assert(!JSON.stringify(entries).includes('BOB_PRIVATE'));
  assert.equal((await list(bob)).entries[0].content,'BOB_PRIVATE');
  await assert.rejects(list({...alice,identityId:bob.identityId}),/本人/);
  await assert.rejects(list({...alice,authKind:'service'}),/本人/);
  const bobEntry=(await list(bob)).entries[0];
  await assert.rejects(review({id:bobEntry.id,expectedVersion:1,action:'delete'},alice),/找不到/);
  let entry=entries[0];
  assert(!((await m.buildLearningContext({...await actor(alice),query:'解释'})).includes('ALICE_ONLY')));
  await review({id:entry.id,expectedVersion:entry.version,action:'keep'},alice);
  assert((await m.buildLearningContext({...await actor(alice),query:'解释'})).includes('ALICE_ONLY'));
  assert(!((await m.buildLearningContext({...await actor(bob),query:'解释'})).includes('ALICE_ONLY')));
  await assert.rejects(review({id:entry.id,expectedVersion:1,action:'delete'},alice),/已更新/);
  entry=(await list(alice)).entries[0];
  await review({id:entry.id,expectedVersion:entry.version,action:'edit',content:'ALICE_EDITED',conditions:'解释新概念',exceptions:'紧急时简短'},alice);
  entry=(await list(alice)).entries[0];assert.equal(entry.content,'ALICE_EDITED');assert.equal(entry.exceptions,'紧急时简短');
  await updateAuthDocument(d=>{d.people.find(p=>p.id===alice.personId).preferences.personalMemory.enabled=false;});
  assert(!((await m.buildLearningContext({...await actor(alice),query:'解释'})).includes('ALICE_EDITED')));
  await review({id:entry.id,expectedVersion:entry.version,action:'delete'},alice);
  assert.equal((await list(alice)).entries.length,0,'deletion remains available while paused');
  const profile=m.learningPaths(memoryDir,alice.personId).profile;
  assert.equal((await m.readPersonalProfile(profile,{entryId:entry.id,details:true})).entries[0].status,'withdrawn');
  assert(!(await readFile(profile,'utf8')).includes('ALICE_'));
  const run=promisify(execFile);
  await assert.rejects(run('rg',['-l','-F','ALICE_EDITED',memoryDir]),e=>e.code===1,'ordinary recursive search excludes private archives');
  // Move to the old location, then check lossless locked migration and search exclusion.
  const hidden=join(memoryDir,'reference','people','.person_alice.md.store');
  await rename(hidden,profile+'.store');
  const before=JSON.stringify((await m.readPersonalProfile(profile,{details:true})).entries);
  const migration=await m.migratePersonalProfile(profile);assert.equal(migration.relocated,true);
  assert.equal(JSON.stringify((await m.readPersonalProfile(profile,{details:true})).entries),before);
  await assert.rejects(run('rg',['-l','-F','ALICE_EDITED',memoryDir]),e=>e.code===1);
  const method=await m.applyLearningUpdates({...await actor(alice),sources:source,updates:[{key:'shared',kind:'method',scope:'instance',content:'must not write',evidence:[{seq:1,quote:source[0].output}]}]});
  assert.equal(method.promotedCount,0);assert.match(method.rejected[0].reason,/disabled/);
  let response;
  await route({pathname:'/api/personal-memory-entries',parsedUrl:{query:{personId:bob.personId}},req:{method:'GET'},res:{},authSession:alice,writeJson:(_r,status,body)=>response={status,body}});
  assert.equal(response.status,403);
  const {handleControlRoutes}=await import('../chat/router-control-routes.mjs');
  await handleControlRoutes({pathname:'/api/memory-context-view',parsedUrl:{query:{personId:bob.personId}},req:{method:'GET'},res:{setHeader(){}},authSession:alice,writeJson:(_r,status,body)=>response={status,body}});
  assert.equal(response.status,403,'the existing memory inspection page also rejects a different person');
  console.log('PASS own-memory review: list, accept, edit, delete while paused, cross-person denial, hidden archives, lossless migration, separate handbook grant');
}finally{await rm(home,{recursive:true,force:true});}
