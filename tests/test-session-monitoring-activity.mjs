import './isolate-test-environment.mjs';
import assert from 'node:assert/strict';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { CHAT_RUNS_DIR } from '../lib/config.mjs';
import { getSessionMonitoringActivity } from '../chat/session-manager.mjs';
const id = 'a'.repeat(32), runId = 'run_' + 'a'.repeat(24), directory = join(CHAT_RUNS_DIR, runId);
await mkdir(directory, { recursive: true });
const status = { id: runId, sessionId: id, state: 'running', startedAt: new Date().toISOString() };
await writeFile(join(directory, 'status.json'), JSON.stringify(status));
await writeFile(join(directory, 'native-question.json'), JSON.stringify({ id: 'q', state: 'pending', question: { text: 'private question' } }));
const before = await readFile(join(directory, 'status.json'), 'utf8');
const running = await getSessionMonitoringActivity({ id, activeRunId: runId });
assert.equal(running.run.state, 'running');
assert.equal(running.run.waiting, true);
assert(!JSON.stringify(running).includes('private question'));
assert.equal(await readFile(join(directory, 'status.json'), 'utf8'), before);
await writeFile(join(directory, 'status.json'), JSON.stringify({ ...status, state: 'completed' }));
assert.equal((await getSessionMonitoringActivity({ id, activeRunId: runId })).run.state, 'idle');
assert.equal((await getSessionMonitoringActivity({ id, activeRunId: 'run_' + 'b'.repeat(24) })).run.state, 'unknown');
assert.equal((await getSessionMonitoringActivity({ id })).run.state, 'idle');
console.log('monitoring activity: live wait, terminal, missing metadata, privacy and no reconciliation passed');
process.exit(0);
