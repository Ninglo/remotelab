import './isolate-test-environment.mjs';
import assert from 'node:assert/strict';
import { mkdtemp, rm, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { createUsageEventStore, normalizeUsageEvent } from '../chat/usage-events.mjs';
import { createContextQueryObserver, summarizeContextQueries } from '../chat/context-query-monitoring.mjs';
import { createHash } from 'node:crypto';
import { observeAcceptedRules, observeContextRule } from '../chat/context-rule-monitoring.mjs';
import { reverseLedgerLines } from '../chat/context-query-ledger-reader.mjs';
const directory = await mkdtemp(join(tmpdir(), 'context-query-'));
try {
  const store = createUsageEventStore({ directory });
  const observe = createContextQueryObserver(store);
  const input = { sessionId: 'session_a', runId: 'run_a', kind: 'work', query: 'private query' };
  const value = { related: [], candidates: [{ body: 'private result' }], background: { coverage: [] } };
  assert.equal(await observe(input, async () => value), value);
  await observe(input, async () => ({ candidates: [], background: { sourceCoverage: [{ result: 'partial' }] } }));
  const expected = Object.assign(Error('private error'), { code: 'ENOENT' });
  await assert.rejects(observe(input, async () => { throw expected; }), e => e === expected);
  await observe({ ...input, sessionId: 'session_b' }, async () => value);
  await store.record({ eventId: 'interrupted', event: 'context_query', state: 'started', kind: 'memory', sessionId: 'session_a', attemptId: 'interrupted', timestamp: Date.now() });
  const query = await store.query({ contextOnly: true, sessionId: 'session_a' });
  const report = summarizeContextQueries(query);
  assert.deepEqual(report.summary, { attempts: 4, succeeded: 1, partial: 1, failed: 1, unfinished: 1, repeated: 3 });
  assert.equal(report.records.find(r => r.state === 'succeeded').resultCount, 1);
  assert.equal(report.records.find(r => r.state === 'failed').errorCode, 'ENOENT');
  assert(!JSON.stringify(report).includes('private'));
  assert(report.collectionStartedAt);
  // Restart reader and same-ID replay do not inflate counts.
  const reopened = createUsageEventStore({ directory });
  await reopened.record(query.events);
  assert.equal(summarizeContextQueries(await reopened.query({ contextOnly: true, sessionId: 'session_a' })).summary.attempts, 4);
  const scope = { sessionId: 'session_a', runId: 'run_a' };
  const hash = createHash('sha256').update(JSON.stringify(scope.sessionId)).digest('hex').slice(0, 24);
  const ruleInput = { id: 'rule_input', text: `## Current RemoteLab rules\nIt is unchanged from the previous accepted input;\nRecovery snapshot: ${directory}/rule-context/${hash}/${'a'.repeat(64)}.json.` };
  await observeAcceptedRules(ruleInput, { accepted: false }, scope, store, directory);
  await observeAcceptedRules(ruleInput, { accepted: true }, { ...scope, sessionId: 'session_b' }, store, directory);
  await observeAcceptedRules(ruleInput, { accepted: true }, scope, store, directory);
  await observeAcceptedRules(ruleInput, { accepted: true }, scope, store, directory);
  await observeContextRule(scope, { kind: 'recovery', state: 'started', attemptId: 'restore-a', timestamp: 1 }, store);
  await observeContextRule(scope, { kind: 'recovery', state: 'failed', attemptId: 'restore-a', timestamp: Date.now(), errorCode: 'ENOENT', text: 'private rules' }, store);
  await observeContextRule(scope, { kind: 'recovery', state: 'started', attemptId: 'restore-b', timestamp: Date.now() }, store);
  await observeContextRule(scope, { kind: 'compaction', state: 'compacted', timestamp: Date.now() }, store);
  const merged = summarizeContextQueries(await store.query({ contextOnly: true, sessionId: scope.sessionId }));
  assert.equal(merged.summary.attempts, 4, 'rule events must not inflate query counts');
  assert.equal(merged.rules.summary.accepted, 1, 'only matching Session accepted input; retries deduplicated');
  assert.equal(merged.rules.summary.failed, 1); assert.equal(merged.rules.summary.unfinished, 1);
  assert.equal(merged.rules.summary.compacted, 1); assert(merged.rules.collectionStartedAt);
  assert.equal(merged.rules.records.find(x => x.state === 'accepted').kind, 'reference');
  await observeAcceptedRules({ id: 'delta_input', text: ruleInput.text.replace('It is unchanged from the previous accepted input;',
    'Only these slots changed: project_memory.') }, { accepted: true }, scope, store, directory);
  assert.equal(summarizeContextQueries(await store.query({ contextOnly: true, sessionId: scope.sessionId }))
    .rules.records.find(x => x.requestId === 'delta_input').kind, 'delta');
  assert(!JSON.stringify(merged).includes('private rules'));
  await observeContextRule(scope, { state: 'started' }, { record: async () => { throw Error('disk'); } });
  const fixture = join(directory, 'reverse-test');
  const line = JSON.stringify({ text: '中文内容'.repeat(200) });
  await writeFile(fixture, `${Array(300).fill(line).join('\n')}\n${'z'.repeat(90000)}\n${line}\nlatest\n`);
  let budget = { remaining: 4096, incomplete: false }, reversed = [];
  for await (const line of reverseLedgerLines(fixture, budget)) reversed.push(line);
  assert.equal(reversed[0], 'latest'); assert.equal(reversed[1], line); assert(budget.incomplete);
  budget = { remaining: 2 * 1024 * 1024, incomplete: false }; reversed = [];
  for await (const line of reverseLedgerLines(fixture, budget)) reversed.push(line);
  assert.equal(reversed.length, 303); assert.equal(reversed[2].length, 4097);
  assert.equal(reversed.at(-1), line); assert.equal(budget.incomplete, false);
  const limited = await reopened.query({ contextOnly: true, sessionId: 'session_a', maxScanned: 1 });
  assert(limited.coverage.incomplete);
  assert.equal(normalizeUsageEvent({ ...query.events[0], query: 'private', body: 'private' }).query, undefined);
  assert.equal(normalizeUsageEvent({ ...query.events[0], state: 'invented' }), null);
  const broken = createContextQueryObserver({ record: async () => { throw Error('disk'); } });
  assert.equal(await broken(input, async () => value), value);
  await assert.rejects(broken(input, async () => { throw expected; }), e => e === expected);
  console.log('context lookup monitoring: real results, partial sources, failure, interruption, restart, scope, bounds and privacy passed');
} finally { await rm(directory, { recursive: true, force: true }); }
