import assert from 'node:assert/strict';
import { createServer } from 'node:http';
import { mkdtemp, mkdir, readFile, writeFile, stat, rm, symlink } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createQianyanSourceCredentials } from '../knowledge/qianyan-source-credentials.mjs';
import { createQianyanInternalHandler } from '../chat/router-qianyan-internal-routes.mjs';

const dir = await mkdtemp(join(tmpdir(), 'qianyan-key-input-'));
let server;
try {
  const configDir = join(dir, 'config'), project = join(dir, 'project');
  await mkdir(configDir); await mkdir(project);
  await writeFile(join(configDir, 'qianyan-internal.json'), JSON.stringify({ sourceCredentialPersonIds: ['contributor'] }));
  const staff = { id: 'contributor', name: '测试员工', auth_kind: 'remotelab' };
  const people = { contributor: staff, other: { ...staff, id: 'other' }, service: { ...staff, auth_kind: 'service' } };
  let clock = 1000;
  const sourceCredentialService = createQianyanSourceCredentials({ configDir, project, now: () => clock });
  const handler = createQianyanInternalHandler({ sourceCredentialService, identityService: { member: async req => people[req.headers['x-test-person']] }, remoteSession: async () => null });
  server = createServer((req, res) => handler({ req, res, pathname: new URL(req.url, 'http://localhost').pathname,
    writeJson: (r, status, value) => { r.writeHead(status, { 'Content-Type': 'application/json' }); r.end(JSON.stringify(value)); } }));
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const origin = `http://127.0.0.1:${server.address().port}`, endpoint = origin + '/api/qianyan/internal/source-credentials';
  const headers = person => ({ 'x-test-person': person });
  const page = async (person = 'contributor') => { const r = await fetch(endpoint, { headers: headers(person) }); return { r, html: await r.text() }; };
  const token = html => html.match(/'X-Form-Token':'([a-f0-9]{64})'/)[1];
  const submit = (key, formToken, person = 'contributor', from = origin) => fetch(endpoint, { method: 'POST', headers: { ...headers(person), Origin: from, 'Content-Type': 'application/json', 'X-Form-Token': formToken }, body: JSON.stringify({ key }) });
  assert.equal((await page('unknown')).r.status, 401);
  assert.equal((await page('other')).r.status, 403);
  assert.equal((await page('service')).r.status, 403, 'service tokens cannot enter a human credential form');
  assert.equal((await fetch(endpoint + '/status', { headers: headers('other') })).status, 403);
  const first = await page();
  assert.equal(first.r.status, 200);
  assert.match(first.r.headers.get('cache-control'), /no-store/);
  assert.match(first.r.headers.get('content-security-policy'), /default-src 'none'.*frame-ancestors 'none'/);
  assert.match(first.html, /type="password"/);
  assert.ok(!/localStorage|sessionStorage|console\./.test(first.html), 'credential page has no browser persistence or console logging');
  assert.equal((await submit('dummy-private-api-key', undefined)).status, 403);
  assert.equal((await submit('dummy-private-api-key', token(first.html), 'other')).status, 403);
  assert.equal((await submit('dummy-private-api-key', token(first.html), 'contributor', 'https://foreign.example')).status, 403);
  assert.equal((await submit('dummy-private-api-key', token(first.html), 'service')).status, 403);
  const saved = await submit('dummy-private-api-key', token(first.html));
  assert.equal(saved.status, 200);
  assert.deepEqual(await saved.json(), { saved: true, configured: true });
  const path = join(project, 'private/secrets/source-providers.json');
  assert.equal((await stat(path)).mode & 0o777, 0o600);
  assert.equal((await stat(join(project, 'private/secrets'))).mode & 0o777, 0o700);
  assert.equal(JSON.parse(await readFile(path, 'utf8')).DAJIALA_KEY, 'dummy-private-api-key');
  assert.equal((await submit('replacement-private-key', token(first.html))).status, 403, 'used form tokens cannot replay');
  const status = await fetch(endpoint + '/status', { headers: headers('contributor') });
  assert.deepEqual(await status.json(), { configured: true }, 'status never returns a key, suffix or prefix');
  assert.ok(!(await page()).html.includes('dummy-private-api-key'), 'existing key cannot be fetched by opening the page');
  const expired = await page(); clock += 11 * 60000;
  assert.equal((await submit('replacement-private-key', token(expired.html))).status, 403);
  const invalid = await page();
  const invalidResponse = await submit('invalid\nprivate-key', token(invalid.html));
  assert.equal(invalidResponse.status, 400);
  assert.ok(!(await invalidResponse.text()).includes('invalid\nprivate-key'));
  await writeFile(path, JSON.stringify({ DAJIALA_KEY: 'old-key', SOCIALDATA_API_KEY: 'preserved-key' }), { mode: 0o600 });
  const replacing = await page();
  assert.equal((await submit('replacement-private-key', token(replacing.html))).status, 200);
  assert.equal(JSON.parse(await readFile(path, 'utf8')).SOCIALDATA_API_KEY, 'preserved-key', 'changing the MP key preserves the other provider');
  const large = await page();
  assert.equal((await submit('x'.repeat(9000), token(large.html))).status, 413);
  const outside = join(dir, 'outside.json'); await writeFile(outside, '{}');
  await rm(path); await symlink(outside, path);
  const symlinkPage = await page();
  assert.equal((await submit('must-not-be-written', token(symlinkPage.html))).status, 503);
  assert.equal(await readFile(outside, 'utf8'), '{}');
  console.log('Secure source-key form: identity, CSRF, expiry, permissions, no key readback, preservation and symlink boundaries passed.');
} finally {
  if (server) await new Promise(resolve => server.close(resolve));
  await rm(dir, { recursive: true, force: true });
}
