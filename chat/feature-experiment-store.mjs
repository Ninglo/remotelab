import { createHash, randomInt, randomUUID } from 'node:crypto';
import { readFile, mkdir, writeFile, link, unlink, readdir } from 'node:fs/promises';
import { join, dirname } from 'node:path';
import { CONFIG_DIR } from '../lib/config.mjs';

export const EXPERIMENT_ROOT = join(CONFIG_DIR, 'feature-experiments');
export const fingerprint = value => createHash('sha256').update(JSON.stringify(value)).digest('hex');
export const timeMs = value => typeof value === 'number' ? value : Date.parse(value);
export const safeId = value => typeof value === 'string' && /^[a-zA-Z0-9_-]{1,100}$/.test(value);
export async function readRecord(path, fallback = null) {
  try { return JSON.parse(await readFile(path, 'utf8')); }
  catch (error) { if (error.code === 'ENOENT') return fallback; throw error; }
}
// Publish complete bytes exactly once. Competing processes never observe a
// half-written record and never replace the winning random assignment.
export async function publishRecord(path, value) {
  await mkdir(dirname(path), { recursive: true, mode: 0o700 });
  const temp = path + '.tmp-' + randomUUID();
  await writeFile(temp, JSON.stringify(value, null, 2), { mode: 0o600 });
  try { await link(temp, path); }
  catch (error) { if (error.code !== 'EEXIST') throw error; }
  finally { await unlink(temp).catch(() => {}); }
  return readRecord(path);
}
export async function records(directory, limit = 10000) {
  let entries;
  try { entries = (await readdir(directory)).filter(name => name.endsWith('.json')).sort(); }
  catch (error) { if (error.code === 'ENOENT') return { items: [], partial: false }; throw error; }
  const items = [];
  for (const name of entries.slice(0, limit)) items.push(await readRecord(join(directory, name)));
  return { items, partial: entries.length > limit };
}
export function validateSpec(spec) {
  if (spec?.schema !== 1 || !safeId(spec.id) || spec.kind !== 'context-background-v1'
      || !['aa', 'ab'].includes(spec.mode) || !Array.isArray(spec.personIds) || spec.personIds.length !== 1
      || !safeId(spec.personIds[0]) || !Number.isFinite(timeMs(spec.since))
      || !Number.isFinite(spec.sampleRate) || spec.sampleRate <= 0 || spec.sampleRate > 1
      || !Number.isInteger(spec.observationHours) || spec.observationHours < 1 || spec.observationHours > 72
      || !Number.isInteger(spec.maxNightlyCases) || spec.maxNightlyCases < 1 || spec.maxNightlyCases > 50
      || spec.rubricVersion !== 'context-background-v1') throw new Error('Invalid experiment specification');
  return spec;
}
export async function currentExperiment(root = EXPERIMENT_ROOT) {
  const active = await readRecord(join(root, 'active.json'));
  if (!active || !safeId(active.id)) return null;
  const directory = join(root, active.id);
  const spec = validateSpec(await readRecord(join(directory, 'spec.json')));
  if (spec.id !== active.id) throw new Error('Experiment identity mismatch');
  return { active, spec, directory };
}
export function eligibleSession(spec, session, input, verified) {
  const source = input.sourceContext || {};
  return verified && spec.personIds.includes(input.personId) && safeId(session?.id)
    && Number.isFinite(timeMs(session.created || session.createdAt)) && timeMs(session.created || session.createdAt) >= timeMs(spec.since)
    && !session.forkedFromSessionId && !session.internalRole && !session.groupFeed
    && !String(session.externalTriggerId || '').startsWith('trg_')
    && !session.automationHomeTaskId && !input.automated
    && (!source.connector || ['feishu', 'web'].includes(source.connector))
    && typeof input.query === 'string' && input.query.trim() && typeof input.requestId === 'string' && input.requestId;
}
export async function assignSession(experiment, session, input, { verified, draw = () => randomInt(0x1000000) / 0x1000000 } = {}) {
  if (!eligibleSession(experiment.spec, session, input, verified)) return null;
  const path = join(experiment.directory, 'assignments', session.id + '.json');
  let assignment = await readRecord(path);
  if (!assignment && experiment.active.enrollmentEnabled !== false && experiment.active.enabled !== false) {
    const arm = draw() < 0.5 ? 'A' : 'B';
    const sampled = draw() < experiment.spec.sampleRate;
    const at = new Date().toISOString();
    assignment = await publishRecord(path, { schema: 1, experimentId: experiment.spec.id,
      specHash: fingerprint(experiment.spec), sessionId: session.id, personId: input.personId,
      firstRequestId: input.requestId, assignedAt: at, arm, sampled,
      assignedStrategy: experiment.spec.mode === 'ab' && arm === 'A' ? 'automatic-background' : 'on-demand',
      sampleProbability: experiment.spec.sampleRate,
      // Nothing generated by either treatment is permitted in this baseline.
      baseline: sampled ? { query: input.query, sourceContext: input.baselineSourceContext || input.sourceContext || null,
        attachmentCount: input.attachmentCount || 0, connector: input.sourceContext?.connector || 'web' } : null });
  }
  if (assignment && (assignment.specHash !== fingerprint(experiment.spec) || assignment.personId !== input.personId)) {
    throw new Error('Frozen assignment does not match current experiment/person');
  }
  return assignment;
}

export const TAG_VALUES = {
  workType: ['question', 'research', 'writing', 'coding', 'data', 'operations', 'other', 'unknown'],
  initialMaterial: ['none', 'short', 'long', 'unknown'],
  modality: ['text', 'image', 'audio', 'file', 'mixed', 'unknown'],
  requestedWrite: ['yes', 'no', 'unknown'],
};
export const CRITERIA = ['task_completion', 'latest_constraints', 'factual_support', 'human_rework', 'authority_boundary'];
export function validateLabels(packet, labels) {
  if (!Array.isArray(labels) || labels.length !== packet.cases.length) throw new Error('One label row per case required');
  const seen = new Set();
  for (const row of labels) {
    if (seen.has(row.caseId) || !packet.cases.some(c => c.caseId === row.caseId)) throw new Error('Unknown/duplicate label case');
    seen.add(row.caseId);
    if (Object.keys(row.tags || {}).length !== Object.keys(TAG_VALUES).length) throw new Error('Incomplete labels');
    for (const [key, values] of Object.entries(TAG_VALUES)) if (!values.includes(row.tags[key])) throw new Error('Invalid baseline label');
    if (typeof row.reason !== 'string' || !row.reason.trim() || row.reason.length > 2000) throw new Error('Label reason required');
  }
  return labels;
}
export function validateScores(packet, scores) {
  if (!Array.isArray(scores) || scores.length !== packet.cases.length) throw new Error('One score row per case required');
  const seen = new Set();
  for (const row of scores) {
    const evidence = packet.cases.find(c => c.caseId === row.caseId);
    if (!evidence || seen.has(row.caseId)) throw new Error('Unknown/duplicate score case');
    seen.add(row.caseId);
    if (!Array.isArray(row.criteria) || row.criteria.length !== CRITERIA.length) throw new Error('Incomplete rubric');
    const checks = new Set();
    for (const check of row.criteria) {
      if (!CRITERIA.includes(check.id) || checks.has(check.id)) throw new Error('Unknown/duplicate criterion');
      checks.add(check.id);
      if (!['pass', 'partial', 'fail', 'insufficient-evidence'].includes(check.verdict)
          || typeof check.reason !== 'string' || !check.reason.trim() || check.reason.length > 4000
          || !Array.isArray(check.evidenceSeqs)
          || check.evidenceSeqs.some(seq => !evidence.events.some(e => e.seq === seq))) throw new Error('Invalid verdict/evidence');
      if (check.verdict !== 'insufficient-evidence' && !check.evidenceSeqs.length) throw new Error('A judgment needs actual evidence');
      if ((evidence.coverage.partial || evidence.coverage.ongoing || evidence.coverage.missingRunStates)
          && check.id === 'task_completion' && check.verdict === 'pass') {
        throw new Error('Partial evidence cannot certify complete task success');
      }
    }
  }
  return scores;
}
