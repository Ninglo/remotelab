import assert from 'node:assert/strict';
import {mkdtemp,mkdir,writeFile,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
const temp=await mkdtemp(join(tmpdir(),'knowledge-hybrid-test-'));
process.env.REMOTELAB_CONFIG_DIR=join(temp,'config');
try {
  const {KNOWLEDGE_ROOT:root,captureKnowledgePilot,knowledgePilotPrompt,queryKnowledge,readKnowledgeObservations}=await import('../chat/knowledge-pilot.mjs');
  const {appendEvent}=await import('../chat/history.mjs');
  const corpus=join(temp,'corpus');await mkdir(corpus,{recursive:true});await mkdir(root,{recursive:true});
  const pages=['a.md','b.md','c.md'].map((file,i)=>({file,title:'题'+i,whenToUse:'测试条件',sources:[{id:'s'+i,title:'测试原始记录'}]}));
  await writeFile(join(corpus,'index.json'),JSON.stringify({version:'fixture',pages}));
  for(const p of pages)await writeFile(join(corpus,p.file),'# 条目\n\n测试证据');
  const config={version:1,id:'test',projectId:'test',enabled:true,name:'test',personIds:['person_a'],corpusPath:corpus};
  const options={viewPersonId:'person_a',initiatedByIdentityId:'identity_a'};
  await writeFile(join(root,'config.json'),JSON.stringify(config));
  const before=await captureKnowledgePilot(options);
  const retrieval={strategy:'hybrid-rerank-v1',python:'/runtime/python',embeddingModelPath:'/runtime/embed',rerankerModelPath:'/runtime/rank'};
  await writeFile(join(root,'config.json'),JSON.stringify({...config,retrieval}));
  const after=await captureKnowledgePilot(options);
  assert.match(knowledgePilotPrompt(before,'old'),/完整问题目录/);
  assert.match(knowledgePilotPrompt(after,'new'),/直接返回少量原文片段/);
  assert.doesNotMatch(knowledgePilotPrompt(after,'new'),/完整问题目录/);
  assert.equal(await captureKnowledgePilot({...options,viewPersonId:'person_b'}),null);
  let calls=0,hashes=[];
  const retrieve=async(_config,input)=>{calls++;hashes.push(input.corpusHash);return {passages:input.pages.map(p=>({page:p.file,section:'条目',applies:p.whenToUse,text:p.text})),metrics:{indexBuilt:calls===1}};};
  const r={sessionId:'test-hybrid',requestId:'new',runId:'run_fixture',options:{...options,knowledgePilot:after}};
  const old={...r,requestId:'old',options:{...options,knowledgePilot:before}};
  assert.equal((await queryKnowledge(old,{action:'search',query:'测试',operationId:'old'},{retrieve})).retrievalStrategy,'catalog-routing-v1');
  assert.equal(calls,0,'accepted catalog policy must not change after configuration switch');
  const input={action:'search',query:'措辞不同的测试',operationId:'hybrid'};
  const result=await queryKnowledge(r,input,{retrieve});
  assert.equal(result.kind,'body');assert.equal(result.passages.length,3);assert.equal(Object.keys(result.sources).length,3);
  assert.equal(result.catalog,undefined);assert.ok(result.passages.every(p=>p.pageHash&&p.title));
  assert.equal((await queryKnowledge(r,input,{retrieve})).replayed,true);assert.equal(calls,1);
  await writeFile(join(corpus,'a.md'),'# 条目\n\n修正后的证据');
  await queryKnowledge(r,{...input,operationId:'fresh'},{retrieve});assert.notEqual(hashes[0],hashes[1],'body changes invalidate cached index');
  const evidence=await appendEvent(r.sessionId,{type:'tool_result',runId:r.runId,output:'测试检索结果'});
  await queryKnowledge(r,{action:'report',operationId:'report',report:{effect:'helped',reason:'测试片段能作为已读正文',evidenceSeqs:[evidence.seq]}});
  const stats=await readKnowledgeObservations({lookup:async()=>null,meter:async()=>({usage:null}),nativeReceipt:async()=>false});
  assert.equal(stats.totals.bodyReadCalls,2);assert.equal(stats.totals.readInputs,1);
  assert.equal(stats.totals.repeatedReads,3,'two returns of three pages mean three repeats, never a negative count');
  assert.equal(stats.totals.effects.helped,1);
  await assert.rejects(queryKnowledge(r,{...input,operationId:'failure'},{retrieve:async()=>{throw new Error('worker offline');}}),/unavailable/);
  await writeFile(join(root,'config.json'),JSON.stringify({...config,retrieval:{...retrieval,strategy:'catalog-routing-v1'}}));
  assert.equal((await captureKnowledgePilot(options)).retrievalStrategy,'catalog-routing-v1');
  await writeFile(join(root,'config.json'),JSON.stringify({...config,retrieval,enabled:false}));
  await assert.rejects(queryKnowledge(r,{...input,operationId:'disabled'},{retrieve}),/not enabled/);
  console.log('PASS frozen strategy, scoped activation/rollback, bounded body search contract, provenance, retry, corpus invalidation, effect/report accounting, explicit worker failure');
} finally {await rm(temp,{recursive:true,force:true});}
