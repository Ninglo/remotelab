import assert from 'node:assert/strict';
import { RecordingKnobLight } from '../lib/recording/knob-light.mjs';
import { RecordingKeypad } from '../lib/recording/keypad.mjs';

const active = (id, state = 'recording', laneId = 'b') => ({ laneId, recordingId: id, state });
const saved = (id, extra = {}) => ({ id, laneId: 'b', status: 'pending', endedAt: '2026-10-19T06:00:00Z', ...extra });
const light = new RecordingKnobLight('b');
light.update({ active: [], records: [saved('old')] }, 0);
assert.equal(light.frame(0).enabled, false, 'old completed recordings never replay an ending');
light.update({ active: [active('other', 'recording', 'a')], records: [] }, 1);
assert.equal(light.frame(1).enabled, false, 'another microphone cannot light this knob');
light.update({ active: [active('new', 'starting')], records: [] }, 100);
assert.deepEqual(light.frame(100).rgb, [255, 80, 70]);
assert.deepEqual(light.frame(800).rgb, [255, 80, 70], 'starting cannot imply verified PCM');
light.update({ active: [active('new')], records: [] }, 900);
const frames = Array.from({ length: 81 }, (_, i) => light.frame(900 + i * 50));
assert.equal(Math.min(...frames.map(f => f.brightness)), 15);
assert.equal(Math.max(...frames.map(f => f.brightness)), 35);
assert.ok(frames.every(f => f.enabled));
light.update({ active: [], records: [saved('new')] }, 5000);
assert.deepEqual(light.frame(5000).rgb, [255, 210, 160]);
assert.equal(light.frame(6701).enabled, false);
light.update({ active: [], records: [saved('new', { status: 'submitted' })] }, 7000);
assert.equal(light.frame(7000).enabled, false, 'upload progress must not repeat ending');
light.update({ active: [active('failed')], records: [] }, 8000);
light.update({ active: [], records: [saved('failed', { interrupted: true, error: 'receiver disconnected' })] }, 9000);
assert.equal(light.phase, 'error');
assert.deepEqual(light.frame(9000).rgb, [255, 80, 70]);
light.reset();
assert.equal(light.frame(9100).enabled, false, 'service loss clears the recording indicator');
light.update({ active: [active('adopted')], records: [] }, 10000);
assert.deepEqual(light.frame(10000).rgb, [100, 160, 255], 'restarting silently adopts active recording');
light.update({ active: [], records: [] }, 11000);
assert.equal(light.phase, 'error', 'a disappearing active recording without saved evidence is not success');

const binding = { deviceId: 'knob', usagePage: 7, key: 104, action: 'toggle', laneId: 'b' };
const keypad = new RecordingKeypad([binding]);
assert.equal(keypad.accept({ deviceId: 'other', key: 104, pressed: true }), undefined);
assert.equal(keypad.accept({ deviceId: 'knob', usagePage: 12, key: 104, pressed: true }), undefined);
assert.equal(keypad.accept({ deviceId: 'knob', key: 104, pressed: true }), binding);
assert.equal(keypad.accept({ deviceId: 'knob', key: 104, pressed: true }), undefined, 'held/repeated key cannot toggle twice');
keypad.accept({ deviceId: 'knob', key: 104, pressed: false });
assert.equal(keypad.accept({ deviceId: 'knob', key: 104, pressed: true }), binding);
console.log('knob indicator transitions, failures, restart adoption and F13 toggle verified');
