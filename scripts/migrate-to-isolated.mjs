#!/usr/bin/env node

/**
 * One-time migration: convert all non-isolated guest instances to isolated mode.
 *
 * For each instance:
 *   1. Stop the service
 *   2. Create dedicated Linux user (remotelab-<name>)
 *   3. Move instance data from ~/.remotelab/instances/<name> to /var/lib/remotelab-guests/<name>
 *   4. Seed AI tool credentials
 *   5. chown everything to the new user
 *   6. Write systemd isolation override
 *   7. Rewrite env file with new HOME + INSTANCE_ROOT, restrict permissions
 *   8. Update registry record
 *   9. Restart service + health check
 */

import { execFile as execFileCallback } from 'child_process';
import { copyFile, mkdir, readFile, rename, stat, writeFile } from 'fs/promises';
import { homedir } from 'os';
import { join, dirname } from 'path';
import { promisify } from 'util';
import {
  writeGuestCodexAuthFile,
  writeGuestCodexConfigFile,
} from '../lib/codex-auth-redaction.mjs';

const execFileAsync = promisify(execFileCallback);

const HOME_DIR = homedir();
const GUEST_REGISTRY_FILE = join(HOME_DIR, '.config', 'remotelab', 'guest-instances.json');
const GUEST_HOMES_ROOT = '/var/lib/remotelab-guests';
const GUEST_ENV_DIR = '/etc/remotelab/guest-instances';
const SYSTEMD_DIR = '/etc/systemd/system';

function trimString(value) {
  return typeof value === 'string' ? value.trim() : '';
}

async function pathExists(path) {
  try { await stat(path); return true; } catch { return false; }
}

async function exec(command, args, description) {
  try {
    const result = await execFileAsync(command, args, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] });
    return result.stdout || '';
  } catch (error) {
    const stderr = trimString(error?.stderr || '');
    const stdout = trimString(error?.stdout || '');
    const details = stderr || stdout || trimString(error?.message || '');
    throw new Error(`${description} failed: ${details}`);
  }
}

async function writeAtomic(filePath, content) {
  const tmpPath = `${filePath}.tmp.${Date.now()}`;
  await writeFile(tmpPath, content, 'utf8');
  await rename(tmpPath, filePath);
}

function buildOverrideContent(name) {
  const userName = `remotelab-${name}`;
  const homePath = join(GUEST_HOMES_ROOT, name);
  return [
    '# Auto-generated by RemoteLab guest-instance isolation',
    '# This override restricts the service to a dedicated OS user with sandbox hardening.',
    '[Service]',
    `User=${userName}`,
    `Group=${userName}`,
    '',
    '# Filesystem isolation',
    'ProtectHome=yes',
    'PrivateTmp=yes',
    'ProtectSystem=strict',
    'ReadOnlyPaths=/opt/remotelab',
    `ReadWritePaths=${homePath}`,
    `ReadWritePaths=/var/log/remotelab`,
    '',
    '# Process isolation — hides other users\' processes from /proc and ps',
    'ProtectProc=invisible',
    'ProcSubset=pid',
    '',
    '# Privilege lockdown',
    'NoNewPrivileges=yes',
    '',
  ].join('\n');
}

function parseEnvFile(content = '') {
  const env = {};
  for (const line of String(content).split('\n')) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const sep = trimmed.indexOf('=');
    if (sep <= 0) continue;
    env[trimmed.slice(0, sep).trim()] = trimmed.slice(sep + 1).trim();
  }
  return env;
}

function serializeEnvFile(env = {}) {
  return Object.entries(env)
    .filter(([k, v]) => k && v)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([k, v]) => `${k}=${v}`)
    .join('\n') + '\n';
}

async function migrateInstance(record, dryRun = false) {
  const name = record.name;
  const userName = `remotelab-${name}`;
  const newHome = join(GUEST_HOMES_ROOT, name);
  const oldRoot = trimString(record.instanceRoot);
  const envFile = join(GUEST_ENV_DIR, `${name}.env`);
  const serviceName = `remotelab-guest@${name}.service`;

  console.log(`\n── Migrating ${name} ──`);

  // Skip if already isolated
  if (trimString(record.isolatedUser)) {
    console.log(`  SKIP: already isolated (${record.isolatedUser})`);
    return { name, status: 'skipped', reason: 'already isolated' };
  }

  if (dryRun) {
    console.log(`  DRY-RUN: would create user ${userName}, move ${oldRoot} → ${newHome}`);
    return { name, status: 'dry-run' };
  }

  try {
    // 1. Stop the service
    console.log(`  Stopping ${serviceName}...`);
    try {
      await exec('systemctl', ['stop', serviceName], `Stopping ${serviceName}`);
    } catch {
      console.log(`  Warning: service stop failed (may already be stopped)`);
    }

    // 2. Create Linux user (skip if exists)
    let userExists = false;
    try {
      await exec('id', [userName], `Checking user ${userName}`);
      userExists = true;
      console.log(`  User ${userName} already exists`);
    } catch {
      // User doesn't exist, create it
    }

    if (!userExists) {
      console.log(`  Creating user ${userName}...`);
      await exec('/usr/sbin/useradd', [
        '--system',
        '--home-dir', newHome,
        '--create-home',
        '--shell', '/usr/sbin/nologin',
        userName,
      ], `Creating user ${userName}`);
    }

    // Ensure parent dir permissions
    await exec('chmod', ['711', GUEST_HOMES_ROOT], 'Restricting guest homes root');

    // 3. Move instance data
    if (oldRoot && oldRoot !== newHome && await pathExists(oldRoot)) {
      // If newHome was created by useradd but is mostly empty, remove its skeleton files first
      // then move old data into it
      console.log(`  Moving data: ${oldRoot} → ${newHome}`);

      // Copy contents from old root to new home (preserving attributes)
      await exec('cp', ['-a', `${oldRoot}/.`, newHome], `Copying instance data to ${newHome}`);
      // Rename old root as backup
      const backupPath = `${oldRoot}.pre-isolation-backup`;
      if (await pathExists(backupPath)) {
        // Remove old backup if exists
        await exec('rm', ['-rf', backupPath], 'Removing old backup');
      }
      await rename(oldRoot, backupPath);
      console.log(`  Old data backed up to ${backupPath}`);
    } else if (!await pathExists(newHome)) {
      await mkdir(newHome, { recursive: true });
    }

    // Ensure config and memory dirs exist
    await mkdir(join(newHome, 'config'), { recursive: true });
    await mkdir(join(newHome, 'memory'), { recursive: true });
    await mkdir(join(newHome, 'workspace'), { recursive: true });

    // 4. Seed AI credentials
    console.log(`  Seeding AI credentials...`);
    const claudeDir = join(newHome, '.claude');
    await mkdir(claudeDir, { recursive: true });
    const ownerCreds = join(HOME_DIR, '.claude', '.credentials.json');
    if (await pathExists(ownerCreds)) {
      await copyFile(ownerCreds, join(claudeDir, '.credentials.json'));
    }
    const codexDir = join(newHome, '.codex');
    await mkdir(codexDir, { recursive: true });
    const ownerCodexAuth = join(HOME_DIR, '.codex', 'auth.json');
    if (await pathExists(ownerCodexAuth)) {
      await writeGuestCodexAuthFile({
        sourcePath: ownerCodexAuth,
        targetPath: join(codexDir, 'auth.json'),
      });
    }
    await writeGuestCodexConfigFile(join(codexDir, 'config.toml'));

    // 5. chown everything
    console.log(`  Setting ownership to ${userName}...`);
    await exec('chown', ['-R', `${userName}:${userName}`, newHome], `chown ${newHome}`);
    await exec('chmod', ['700', newHome], `chmod ${newHome}`);

    // 6. Write systemd override
    console.log(`  Writing systemd isolation override...`);
    const overrideDir = join(SYSTEMD_DIR, `remotelab-guest@${name}.service.d`);
    await mkdir(overrideDir, { recursive: true });
    await writeAtomic(join(overrideDir, 'isolation.conf'), buildOverrideContent(name));

    // 7. Rewrite env file
    console.log(`  Updating env file...`);
    if (await pathExists(envFile)) {
      const env = parseEnvFile(await readFile(envFile, 'utf8'));
      env.HOME = newHome;
      env.REMOTELAB_INSTANCE_ROOT = newHome;
      await writeAtomic(envFile, serializeEnvFile(env));
      await exec('chmod', ['600', envFile], 'Restricting env file');
      await exec('chown', ['root:root', envFile], 'Setting env file ownership');
    }

    // Restrict env directory
    await exec('chmod', ['700', GUEST_ENV_DIR], 'Restricting env directory');

    // 8. Update registry record
    const newRecord = {
      ...record,
      instanceRoot: newHome,
      configDir: join(newHome, 'config'),
      memoryDir: join(newHome, 'memory'),
      mailboxRoot: join(newHome, 'config', 'agent-mailbox'),
      authFile: join(newHome, 'config', 'auth.json'),
      isolatedUser: userName,
    };

    // 9. Restart service
    console.log(`  Restarting ${serviceName}...`);
    await exec('systemctl', ['daemon-reload'], 'Reloading systemd');
    await exec('systemctl', ['start', serviceName], `Starting ${serviceName}`);

    // Health check
    const localUrl = trimString(record.localBaseUrl) || `http://127.0.0.1:${record.port}`;
    let healthy = false;
    for (let attempt = 0; attempt < 10; attempt++) {
      await new Promise(r => setTimeout(r, 2000));
      try {
        const response = await fetch(`${localUrl}/api/build-info`);
        if (response.ok) {
          healthy = true;
          break;
        }
      } catch {}
    }

    if (healthy) {
      console.log(`  ✓ ${name} healthy on ${localUrl}`);
    } else {
      console.log(`  ✗ ${name} failed health check on ${localUrl}`);
    }

    return { name, status: healthy ? 'migrated' : 'migrated-unhealthy', record: newRecord };
  } catch (error) {
    console.error(`  ✗ ${name} migration failed: ${error.message}`);
    // Try to restart with old config
    try {
      await exec('systemctl', ['daemon-reload'], 'Reloading systemd');
      await exec('systemctl', ['start', serviceName], `Restarting ${serviceName}`);
    } catch {}
    return { name, status: 'failed', error: error.message };
  }
}

async function main() {
  const args = process.argv.slice(2);
  const dryRun = args.includes('--dry-run');
  const jsonOutput = args.includes('--json');

  console.log(`RemoteLab Guest Instance Isolation Migration`);
  console.log(`Mode: ${dryRun ? 'DRY RUN' : 'LIVE'}`);
  console.log(`Time: ${new Date().toISOString()}`);

  // Load registry
  let registry;
  try {
    registry = JSON.parse(await readFile(GUEST_REGISTRY_FILE, 'utf8'));
  } catch {
    console.error('Failed to load guest registry');
    process.exit(1);
  }

  const nonIsolated = registry.filter(r => !trimString(r.isolatedUser));
  console.log(`\nTotal instances: ${registry.length}`);
  console.log(`Already isolated: ${registry.length - nonIsolated.length}`);
  console.log(`To migrate: ${nonIsolated.length}`);

  if (nonIsolated.length === 0) {
    console.log('\nNothing to migrate.');
    process.exit(0);
  }

  // Ensure root directory
  if (!dryRun) {
    await mkdir(GUEST_HOMES_ROOT, { recursive: true });
  }

  // Migrate each instance
  const results = [];
  for (const record of registry) {
    const result = await migrateInstance(record, dryRun);
    results.push(result);
  }

  // Update registry with new records
  if (!dryRun) {
    const updatedRegistry = registry.map(original => {
      const migrationResult = results.find(r => r.name === original.name);
      if (migrationResult?.record) {
        return migrationResult.record;
      }
      return original;
    });
    const backupPath = `${GUEST_REGISTRY_FILE}.pre-isolation-backup`;
    await copyFile(GUEST_REGISTRY_FILE, backupPath);
    await writeAtomic(GUEST_REGISTRY_FILE, JSON.stringify(updatedRegistry, null, 2));
    console.log(`\nRegistry updated. Backup at ${backupPath}`);
  }

  // Summary
  const migrated = results.filter(r => r.status === 'migrated').length;
  const unhealthy = results.filter(r => r.status === 'migrated-unhealthy').length;
  const failed = results.filter(r => r.status === 'failed').length;
  const skipped = results.filter(r => r.status === 'skipped' || r.status === 'dry-run').length;

  console.log(`\n── Summary ──`);
  console.log(`Migrated:  ${migrated}`);
  console.log(`Unhealthy: ${unhealthy}`);
  console.log(`Failed:    ${failed}`);
  console.log(`Skipped:   ${skipped}`);

  if (jsonOutput) {
    console.log(JSON.stringify(results, null, 2));
  }

  if (failed > 0) process.exit(1);
}

main().catch(err => {
  console.error(err);
  process.exit(1);
});
