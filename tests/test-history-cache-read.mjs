import assert from 'node:assert/strict';
import fsp from 'node:fs/promises';
import { syncBuiltinESMExports } from 'node:module';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { setIsolatedTestHome } from './isolate-test-environment.mjs';
const root = await fsp.mkdtemp(join(tmpdir(), 'history-read-cache-'));
setIsolatedTestHome(root);
let reads = 0, bodyReads = 0;
const originalRead = fsp.readFile.bind(fsp);
fsp.readFile = async function(path, ...args) { if (String(path).includes('/chat-history/')) { reads++; if (String(path).includes('/bodies/')) bodyReads++; } return originalRead(path, ...args); };
syncBuiltinESMExports();
try {
  const writer = await import('../chat/history.mjs');
  const text = 'large real body '.repeat(1000);
  await writer.appendEvent('fixture', { type: 'tool_result', runId: 'old', output: text });
  await writer.appendEvent('fixture', { type: 'message', role: 'assistant', runId: 'new', content: 'answer' });
  const cold = await import('../chat/history.mjs?cache-read-fixture');
  const first = await cold.loadHistory('fixture', { cacheRead: false });
  const before = reads, bodyBefore = bodyReads;
  assert.deepEqual(await cold.loadHistory('fixture', { cacheRead: false }), first);
  assert(reads > before, 'a background miss must not populate persistent caches');
  assert.equal(bodyReads, bodyBefore + 1, 'background hydration must not populate the body cache either');
  await cold.loadHistory('fixture');
  const hot = reads;
  assert.deepEqual(await cold.loadHistory('fixture', { cacheRead: false }), first);
  assert.equal(reads, hot, 'background scans still use existing hot data');
  const selected = await cold.loadHistory('fixture', { bodyTypes: ['message'] });
  assert.equal(selected[0].bodyLoaded, false);
  assert.equal(selected[1].content, 'answer');
  assert.equal((await cold.loadHistory('fixture', { bodyRunId: 'new' }))[0].bodyLoaded, false);
  assert.equal((await cold.readEventBody('fixture', 1, { cacheRead: false })).value, text);
  const { CHAT_HISTORY_DIR } = await import('../lib/config.mjs');
  await fsp.unlink(join(CHAT_HISTORY_DIR, 'fixture', 'bodies', `${first[0].bodyRef}.txt`));
  const missing = await import('../chat/history.mjs?missing-body-fixture');
  await assert.rejects(missing.loadHistory('fixture', { cacheRead: false }), { code: 'ENOENT' });
  assert.equal((await missing.loadHistory('fixture', { bodyTypes: ['message'] }))[1].content, 'answer');
  const { loadCompletedTurnContext } = await import('../chat/session-turn-context.mjs');
  const turn = await loadCompletedTurnContext('fixture', 'new', { loadSessionHistory: missing.loadHistory, includePriorContext: false });
  assert.equal(turn.assistantTurnText, 'answer', 'memory extraction needs no old tool body');
  console.log('PASS: cache admission, hot reuse, selective hydration and explicit missing-body failure');
} finally { fsp.readFile = originalRead; syncBuiltinESMExports(); await fsp.rm(root, { recursive: true, force: true }); }
